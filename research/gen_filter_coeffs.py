"""Generates filter coefficients and constants for the firmware.

Output: firmware/lib/grounded_dsp/filter_coeffs.h
Generated instead of copied by hand, so the filter tested in Python and the filter
on the device are always the same.
"""
import math
from pathlib import Path

from scipy.signal import butter

OUT = Path(__file__).resolve().parent.parent / "firmware/lib/grounded_dsp/filter_coeffs.h"

RESP_FS, ECG_FS = 25, 250
resp_sos = butter(2, [0.05, 1.0], btype="bandpass", fs=RESP_FS, output="sos")
ecg_sos = butter(2, [5, 15], btype="bandpass", fs=ECG_FS, output="sos")


def alpha(tau_s, fs):
    """Exponential moving-average coefficient (same formula as breath_detector.py)."""
    return 1.0 - math.exp(-1.0 / (tau_s * fs))


def c_float(v):
    """C float literal: 9 digits represent a float32 losslessly; '1f' is invalid, it must be '1.0f'."""
    s = f"{v:.9g}"
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def sos_array(name, sos):
    rows = ",\n".join("    {" + ", ".join(c_float(v) for v in s) + "}" for s in sos)
    return f"static const float {name}[{len(sos)}][6] = {{\n{rows}\n}};\n"


text = f"""// AUTO-GENERATED by research/gen_filter_coeffs.py
// Do not edit by hand; change the Python script and regenerate.
#pragma once

// Respiration: {RESP_FS} Hz, 2nd-order Butterworth bandpass 0.05-1.0 Hz
#define RESP_FS {RESP_FS}
#define RESP_SOS_N {len(resp_sos)}
{sos_array("RESP_SOS", resp_sos)}
static const float BREATH_ALPHA_FAST = {c_float(alpha(4.0, RESP_FS))};   // tau = 4 s
static const float BREATH_ALPHA_SLOW = {c_float(alpha(60.0, RESP_FS))};  // tau = 60 s

// ECG: {ECG_FS} Hz, 2nd-order Butterworth bandpass 5-15 Hz
#define ECG_FS {ECG_FS}
#define ECG_SOS_N {len(ecg_sos)}
{sos_array("ECG_SOS", ecg_sos)}
static const float BEAT_ALPHA_NOISE = {c_float(alpha(1.0, ECG_FS))};  // tau = 1 s
"""

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(text)
print(f"Wrote: {OUT}")
